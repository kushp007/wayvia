import { expect, type Page } from '@playwright/test'

export async function verifySharedTrip(page: Page, guest: Page, authenticateGuest?: () => Promise<void>) {
  const title = 'Shared weekend ' + crypto.randomUUID()
  await page.goto('/home')
  await page.getByRole('button', { name: 'New trip' }).click()
  const trip = page.getByRole('dialog')
  await trip.getByLabel('Trip name').fill(title)
  await trip.getByLabel('Destination').fill('Boston')
  await trip.getByLabel('Start date').fill('2027-03-13')
  await trip.getByLabel('End date').fill('2027-03-15')
  await expect(trip.getByLabel('Cover image URL')).toHaveCount(0)
  await trip.getByRole('button', { name: 'Create trip' }).click()
  await expect(page.getByRole('heading', { name: title })).toBeVisible()

  await page.getByRole('button', { name: 'Invite friends' }).click()
  const invitation = page.getByRole('dialog')
  await invitation.getByRole('button', { name: 'Generate invitation' }).click()
  const link = invitation.getByLabel('Invitation link')
  await expect(link).toHaveValue(/#invite=/)
  await guest.goto(await link.inputValue())
  await authenticateGuest?.()
  await guest.getByRole('button', { name: 'Accept invitation' }).click()
  await expect(guest.getByRole('heading', { name: title })).toBeVisible()
  await expect(invitation.getByText('Collaborator', { exact: true })).toBeVisible()
  await invitation.getByRole('button', { name: 'Close dialog' }).click()

  await Promise.all([page, guest].map(view => view.getByRole('tab', { name: 'Voting' }).click()))
  await guest.getByRole('button', { name: 'Add an idea' }).click()
  const activity = guest.getByRole('dialog')
  await activity.getByLabel('Activity name').fill('Museum tickets')
  await activity.getByLabel('Estimated group cost (USD)').fill('80')
  await activity.getByRole('button', { name: 'Save activity' }).click()
  await expect(page.getByRole('heading', { name: 'Museum tickets' })).toBeVisible()
  await page.getByRole('button', { name: 'Schedule', exact: true }).click()
  const schedule = page.getByRole('dialog')
  await schedule.getByLabel('Itinerary date').fill('2027-03-13')
  await schedule.getByLabel('Time at destination').fill('09:15')
  await schedule.getByRole('button', { name: 'Save activity' }).click()
  await expect(guest.locator('.scheduled-tag')).toHaveText('Mar 13')
  await Promise.all([page, guest].map(view => view.getByRole('button', { name: 'Upvote Museum tickets' }).click()))
  for (const view of [page, guest]) await expect(view.locator('.vote-rail strong')).toHaveText('2')
  await guest.getByRole('button', { name: 'Upvote Museum tickets' }).click()
  await expect(page.locator('.vote-rail strong')).toHaveText('1')

  await page.getByRole('tab', { name: 'Itinerary' }).click()
  await page.getByRole('button', { name: 'Change schedule' }).click()
  await schedule.getByLabel('Itinerary date').fill('2027-03-14')
  await schedule.getByRole('button', { name: 'Save activity' }).click()
  await page.getByRole('button', { name: /DAY 2/ }).click()
  await expect(page.getByRole('heading', { name: 'Museum tickets' })).toBeVisible()

  await page.getByRole('tab', { name: 'Budget' }).click()
  await expect(page.getByText('$80', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('$40', { exact: true })).toBeVisible()

  await guest.reload()
  await expect(guest.getByRole('heading', { name: title })).toBeVisible()
  await guest.getByRole('tab', { name: 'Itinerary' }).click()
  await guest.getByRole('button', { name: /DAY 2/ }).click()
  await expect(guest.getByRole('heading', { name: 'Museum tickets' })).toBeVisible()
  await guest.getByRole('tab', { name: 'Voting' }).click()
  await expect(guest.locator('.vote-rail strong')).toHaveText('1')

  await page.getByRole('button', { name: 'Invite friends' }).click()
  await invitation.getByRole('button', { name: /^Remove / }).click()
  await invitation.getByRole('button', { name: 'Confirm removal' }).click()
  await expect(guest.locator('aside').getByRole('button', { name: title })).toHaveCount(0)
  await invitation.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Trip options' }).click()
  await page.getByRole('menuitem', { name: 'Delete trip' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete trip' }).click()
  await expect(page.locator('aside').getByRole('button', { name: title })).toHaveCount(0)
  await page.getByRole('link', { name: 'Wayvia home' }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goBack()
  await expect(page.getByTestId('nav-user-name')).toBeVisible()
}
